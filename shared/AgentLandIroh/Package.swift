// swift-tools-version: 6.2
import Foundation
import PackageDescription

// IrohLib.xcframework is built from pinned source by scripts/build-iroh-ffi.sh and is
// not committed (see README.md and third_party/iroh-ffi/README.md). Its files must match
// the committed third_party/iroh-ffi/IrohLib.sha256: the VerifyIrohLib plugin checks
// them before the IrohLib target compiles, so a build that differs never gets linked.
let packageDirectory = URL(fileURLWithPath: #filePath).deletingLastPathComponent()
let xcframework = packageDirectory.appendingPathComponent("Frameworks/IrohLib.xcframework/Info.plist")
if !FileManager.default.fileExists(atPath: xcframework.path) {
    fatalError("shared/AgentLandIroh/Frameworks/IrohLib.xcframework is missing: run scripts/build-iroh-ffi.sh")
}

let package = Package(
    name: "AgentLandIroh",
    platforms: [.iOS(.v26), .macOS(.v26)],
    products: [
        .library(name: "AgentLandIroh", targets: ["AgentLandIroh"])
    ],
    targets: [
        // Static libraries for iOS arm64, the iOS simulator (arm64) and macOS arm64,
        // with the C header of the FFI (module IrohFFI).
        .binaryTarget(name: "IrohFFI", path: "Frameworks/IrohLib.xcframework"),
        // The Swift wrapper generated by uniffi-bindgen (module IrohLib, as upstream).
        .target(
            name: "IrohLib",
            dependencies: ["IrohFFI"],
            // uniffi 0.31's generated async helpers do not pass Swift 6 data-race checks.
            swiftSettings: [.swiftLanguageMode(.v5)],
            // What the static libraries import (nm -u): SystemConfiguration, and on iOS Network.
            linkerSettings: [
                .linkedFramework("SystemConfiguration"),
                .linkedFramework("Network", .when(platforms: [.iOS]))
            ],
            plugins: ["VerifyIrohLib"]
        ),
        // Checks Frameworks/IrohLib.xcframework against third_party/iroh-ffi/IrohLib.sha256.
        .plugin(name: "VerifyIrohLib", capability: .buildTool()),
        .target(name: "AgentLandIroh", dependencies: ["IrohLib"]),
        // Test-only: records connect/send calls to watched ports (port mapper tests).
        .target(name: "IrohSendRecorder", path: "Tests/IrohSendRecorder"),
        .testTarget(name: "AgentLandIrohTests", dependencies: ["AgentLandIroh", "IrohSendRecorder"])
    ]
)
