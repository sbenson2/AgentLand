const { chromium } = require('~/.npm/_npx/81bbc6515d992ace/node_modules/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1100, height: 1300 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const output = path.resolve(__dirname);
  try {
    await page.goto('http://127.0.0.1:8769');
    await page.locator('[data-open-work]').click();
    await page.locator('[data-workspace="Website refresh"]').click();
    await page.waitForTimeout(220);
    assert.equal(await page.locator('[data-explorer]').isVisible(), true, 'Workspace selection must keep the drawer open');
    assert.equal(await page.locator('[data-workspace-title]').textContent(), 'Website refresh');
    await page.locator('[data-explorer-tab="files"]').click();
    await page.locator('[data-tree-toggle="src"]').click();
    assert.equal(await page.locator('[data-open-file="src/tokens.css"]').isVisible(), true);
    await page.locator('[data-explorer-tab="workspaces"]').click();
    await page.locator('[data-workspace="AgentLand"]').click();
    await page.locator('[data-pick="signin"]').click();
    await page.locator('[data-explorer]').waitFor({ state: 'hidden' });
    await page.locator('[data-task-menu]').click();
    const menu = page.locator('[data-task-menu-panel]');
    const bounds = await menu.boundingBox();
    const header = await page.locator('.nav').boundingBox();
    assert.ok(bounds.y >= header.y + header.height - 1);
    await page.locator('.phone').screenshot({ path: path.join(output, 'task-dropdown.png') });
    await page.keyboard.press('Escape');
    assert.equal(await menu.isHidden(), true);
    assert.equal(await page.locator('[data-task-menu]').evaluate(node => node === document.activeElement), true);
    await page.locator('[data-task-menu]').click();
    await menu.locator('[data-tab="readme"]').click();
    assert.equal(await page.locator('[data-current-task-title]').textContent(), 'README.md');
    assert.equal(await menu.isHidden(), true);
    await page.locator('[data-task-menu]').click();
    await menu.locator('[data-close-tab="readme"]').click();
    assert.equal(await menu.isVisible(), true);
    await menu.locator('[data-tab="readme"]').click();
    assert.equal(await page.locator('[data-current-task-title]').textContent(), 'README.md');
    await page.locator('[data-task-menu]').click();
    await page.locator('[data-open-settings]').click();
    assert.equal(await menu.isHidden(), true);
    await page.locator('[data-settings-home]').click();
    await page.locator('.home-context').click();
    await page.locator('.phone').screenshot({ path: path.join(output, 'home-task-menu.png') });
    const area = page.locator('[data-home-actions]');
    const areaBounds = await area.boundingBox();
    const tileBounds = await page.locator('[data-action="New Chat"]').boundingBox();
    await page.locator('[data-action="New Chat"]').click();
    await page.waitForTimeout(80);
    const growing = await page.locator('.home-expansion').boundingBox();
    assert.ok(growing.width > tileBounds.width && growing.width <= areaBounds.width + 1);
    await page.waitForFunction(() => !document.querySelector('[data-home-actions]').hasAttribute('aria-busy'));
    assert.deepEqual(await area.boundingBox(), areaBounds);
    await page.locator('.phone').screenshot({ path: path.join(output, 'home-expanded-chat.png') });
    await page.locator('[data-home-back]').click();
    await page.waitForTimeout(140);
    assert.equal(await page.locator('.home-expansion').isVisible(), true);
    await page.waitForFunction(() => !document.querySelector('[data-home-actions]').hasAttribute('aria-busy'));
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.locator('[data-action="New Terminal"]').click();
    assert.equal(await page.locator('[data-home-choice="terminal:shell"]').isVisible(), true);
    assert.equal(await page.locator('.home-expansion').count(), 0);
    assert.equal(await page.locator('.home-quip').evaluate(node => getComputedStyle(node).animationName), 'none');
    await page.locator('[data-home-back]').click();
    for (const width of [320, 375, 402]) {
      await page.setViewportSize({ width, height: 1100 });
      assert.equal(await page.locator('.screen').evaluate(node => node.scrollWidth > node.clientWidth), false);
    }
    assert.deepEqual(errors, []);
    const result = { passed: true, pageErrors: errors, menuBounds: bounds, growingWidth: growing.width, tileWidth: tileBounds.width, areaWidth: areaBounds.width, checks: ['Workspace drawer stays open and refreshes scope', 'Task dropdown under header', 'Switch close reopen', 'Escape focus and outside dismissal', 'Tile expansion and reverse without layout jump', 'Reduced motion', 'Narrow screen overflow'] };
    fs.writeFileSync(path.join(output, 'home-task-menu-checks.json'), JSON.stringify(result, null, 2) + '\n');
    console.log(JSON.stringify(result));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
