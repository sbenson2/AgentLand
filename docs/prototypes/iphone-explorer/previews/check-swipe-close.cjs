const { chromium } = require('~/.npm/_npx/81bbc6515d992ace/node_modules/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1100, height: 1300 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const output = path.resolve(__dirname);
  const row = (kind, workspace, id = '') => page.locator(`[data-swipe-kind="${kind}"][data-swipe-workspace="${workspace}"]${id ? `[data-swipe-id="${id}"]` : ''}`);
  const swipe = async target => {
    await target.scrollIntoViewIfNeeded();
    const box = await target.boundingBox();
    await page.mouse.move(box.x + box.width - 55, box.y + box.height / 2);
    await page.mouse.down();
    await page.mouse.move(box.x + 8, box.y + box.height / 2, { steps: 8 });
    await page.mouse.up();
  };
  try {
    await page.goto('http://127.0.0.1:8769');
    await page.locator('[data-open-work]').click();
    await page.waitForFunction(() => getComputedStyle(document.querySelector('[data-explorer]')).transform === 'matrix(1, 0, 0, 1, 0, 0)');
    assert.equal(await row('task', 'Website refresh', 'terminal').count(), 1, 'Tasks expose a separate swipe reveal surface');
    await page.locator('.phone').screenshot({ animations: 'disabled', path: path.join(output, 'circus-workspaces.png') });
    await swipe(row('task', 'Website refresh', 'terminal'));
    assert.equal(await row('task', 'Website refresh', 'terminal').count(), 1, 'Full swipe must never close');
    assert.equal(await page.locator('[data-workspace-title]').textContent(), 'AgentLand');
    assert.equal(await page.locator('[data-current-task-title]').textContent(), 'Home');
    assert.equal(await row('task', 'Website refresh', 'terminal').locator('[data-swipe-close]').isVisible(), true);
    await page.locator('.phone').screenshot({ animations: 'disabled', path: path.join(output, 'task-close-revealed.png') });
    await row('task', 'Website refresh', 'terminal').locator('[data-swipe-close]').click();
    assert.equal(await row('task', 'Website refresh', 'terminal').count(), 0);
    assert.equal(await row('task', 'AgentLand', 'terminal').count(), 1, 'Duplicate IDs keep their workspace ownership');
    assert.equal(await page.locator('[data-explorer]').isVisible(), true);
    await row('task', 'AgentLand', 'readme').locator('[data-pick]').focus();
    await page.keyboard.press('ArrowLeft');
    assert.equal(await row('task', 'AgentLand', 'readme').locator('[data-swipe-close]').isVisible(), true);
    await page.keyboard.press('Escape');
    assert.equal(await row('task', 'AgentLand', 'readme').locator('[data-swipe-close]').isHidden(), true);
    assert.equal(await page.locator('[data-explorer]').isVisible(), true);
    await swipe(row('workspace', 'Solo chats'));
    await row('workspace', 'Solo chats').locator('[data-swipe-close]').click();
    assert.equal(await page.locator('[data-workspace="Solo chats"]').count(), 0);
    await swipe(row('workspace', 'AgentLand'));
    await page.locator('.phone').screenshot({ animations: 'disabled', path: path.join(output, 'workspace-close-revealed.png') });
    await row('workspace', 'AgentLand').locator('[data-swipe-close]').click();
    assert.equal(await page.locator('[data-workspace-title]').textContent(), 'Website refresh');
    await swipe(row('workspace', 'Website refresh'));
    await row('workspace', 'Website refresh').locator('[data-swipe-close]').click();
    assert.equal(await page.locator('.explorer-group').count(), 0);
    assert.equal(await page.locator('[data-explorer]').isVisible(), true);
    assert.match(await page.locator('.explorer-pane').textContent(), /No open workspaces/);
    await page.locator('[data-explorer-tab="files"]').click();
    assert.match(await page.locator('.explorer-pane').textContent(), /No open workspace/);
    await page.locator('[data-resume-workspace]').click();
    await page.locator('[data-home-choice="resume:AgentLand"]').click();
    await page.locator('[data-open-work]').click();
    await page.locator('[data-explorer-tab="workspaces"]').click();
    assert.equal(await page.locator('[data-workspace="AgentLand"]').count(), 1);
    await page.locator('[data-explorer-tab="files"]').click();
    assert.equal(await page.locator('[data-open-file="README.md"]').count(), 1);
    await page.setViewportSize({ width: 320, height: 1100 });
    await page.locator('[data-explorer-tab="workspaces"]').click();
    assert.equal(await page.locator('[data-explorer]').evaluate(node => node.scrollWidth > node.clientWidth), false);

    const touchContext = await browser.newContext({ viewport: { width: 402, height: 1100 }, isMobile: true, hasTouch: true });
    const touchPage = await touchContext.newPage();
    touchPage.on('pageerror', error => errors.push(error.message));
    await touchPage.goto('http://127.0.0.1:8769');
    await touchPage.locator('[data-open-work]').click();
    const touchRow = touchPage.locator('[data-swipe-kind="task"][data-swipe-workspace="AgentLand"][data-swipe-id="signin"]');
    const cdp = await touchContext.newCDPSession(touchPage);
    const drag = async (dx, dy) => {
      const box = await touchRow.boundingBox();
      const x = box.x + box.width - 60, y = box.y + box.height / 2;
      await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] });
      for (let step = 1; step <= 6; step++) await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x + dx * step / 6, y: y + dy * step / 6 }] });
      await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
    };
    await drag(0, -90);
    assert.equal(await touchPage.locator('.swipe-row.revealed').count(), 0, 'Vertical scroll must not reveal Close');
    assert.equal(await touchRow.count(), 1);
    await drag(-250, 0);
    assert.equal(await touchRow.count(), 1, 'Touch full swipe only reveals');
    assert.equal(await touchRow.locator('[data-swipe-close]').isVisible(), true);
    await touchRow.locator('[data-swipe-close]').tap();
    assert.equal(await touchRow.count(), 0);
    await touchContext.close();
    assert.deepEqual(errors, []);
    const result = { passed: true, pageErrors: errors, checks: ['Mouse full swipe reveals only', 'Distinct Close tap', 'Duplicate task ID ownership', 'No swipe navigation', 'Keyboard reveal and Escape', 'Inactive active and last workspace close', 'Resume preserves sample files', 'Vertical touch scroll', 'Touch two-step close', '320px no overflow'] };
    fs.writeFileSync(path.join(output, 'swipe-close-checks.json'), JSON.stringify(result, null, 2) + '\n');
    console.log(JSON.stringify(result));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
